# =============================================================================
# release.ps1 — выпуск версии одной командой.
#
# Зачем. Один и тот же текст версии нужен в трёх местах: в CHANGELOG.md,
# в сообщении коммита и в аннотации тега. Руками они рано или поздно
# разъезжаются — опечатка здесь, забыл дописать там. Скрипт убирает место,
# где человек ошибается.
#
# Как. Единственный источник правды — CHANGELOG.md. Заголовок версии там
# пишется один раз, а скрипт его ЧИТАЕТ и подставляет в коммит и в тег.
# Ты вводишь только номер версии, текст не набираешь вообще.
#
# Использование:
#   .\scripts\release.ps1 v0.4.0 -DryRun   # показать, что будет, ничего не делая
#   .\scripts\release.ps1 v0.4.0           # выпустить версию
#
# Скрипт делает: проверяет формат версии, берёт её описание из CHANGELOG.md,
# коммитит, ставит аннотированный тег, отправляет коммиты и тег в GitHub
# и ПРОВЕРЯЕТ, что тег там действительно появился.
#
# Если PowerShell откажется запускать скрипт со словами про ExecutionPolicy,
# разреши скрипты для своего пользователя один раз:
#   Set-ExecutionPolicy -Scope CurrentUser RemoteSigned
#
# ВАЖНО ПРО КОДИРОВКУ ЭТОГО ФАЙЛА.
# Он сохранён в UTF-8 С МЕТКОЙ ПОРЯДКА БАЙТ (BOM) и с концами строк CRLF.
# Это не прихоть: Windows PowerShell 5.1 без BOM считает файл однобайтовым
# и превращает кириллицу в кракозябры. А среди кракозябр попадаются символы
# вроде " и ', которые PowerShell принимает за границы строк — и скрипт
# перестаёт разбираться вообще. Если будешь редактировать файл — сохраняй
# его в UTF-8 with BOM.
# =============================================================================

param(
    # Mandatory означает, что без этого аргумента скрипт не запустится,
    # а спросит значение. Position = 0 позволяет писать номер версии
    # сразу после имени скрипта, без -Version.
    [Parameter(Mandatory = $true, Position = 0)]
    [string]$Version,

    # switch — флаг без значения. Есть в командной строке — значит $true.
    [switch]$DryRun
)

# Останавливаться на первой же ошибке в командлетах PowerShell.
# ВАЖНО: на внешние программы вроде git это НЕ распространяется — они
# сообщают о неудаче кодом возврата, а не исключением. Поэтому ниже
# есть отдельная обёртка Invoke-Git, которая этот код проверяет.
$ErrorActionPreference = 'Stop'

# -----------------------------------------------------------------------------
# Вспомогательные функции
# -----------------------------------------------------------------------------

# Invoke-Git запускает git и падает, если тот вернул ненулевой код.
# Без такой обёртки скрипт молча поехал бы дальше после неудачного коммита —
# и запушил бы не то, что ты думаешь.
function Invoke-Git {
    param([Parameter(ValueFromRemainingArguments = $true)][string[]]$GitArgs)

    Write-Host "  git $($GitArgs -join ' ')" -ForegroundColor DarkGray
    & git @GitArgs
    if ($LASTEXITCODE -ne 0) {
        throw "команда 'git $($GitArgs -join ' ')' завершилась с кодом $LASTEXITCODE"
    }
}

# Write-Utf8NoBom записывает текст в файл строго в UTF-8 БЕЗ метки порядка байт.
#
# Зачем такие сложности вместо обычного Set-Content. В Windows PowerShell 5.1
# Set-Content -Encoding UTF8 дописывает в начало файла три невидимых байта —
# так называемый BOM. Git примет их за часть первой строки, и сообщение
# коммита начнётся с мусора. На кириллице это особенно обидно: текст
# и так рискует поехать, а тут ещё и BOM.
function Write-Utf8NoBom {
    param([string]$Path, [string]$Text)
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Text, $utf8NoBom)
}

# -----------------------------------------------------------------------------
# 1. Идём в корень репозитория
# -----------------------------------------------------------------------------

# Скрипт лежит в scripts/, а работать надо из корня проекта — иначе
# CHANGELOG.md не найдётся, если запустить скрипт из другой папки.
# $PSScriptRoot — папка, в которой лежит сам скрипт.
$repoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $repoRoot

# -----------------------------------------------------------------------------
# 2. Проверяем формат версии
# -----------------------------------------------------------------------------

# Регулярное выражение: v, потом три числа через точку, и ничего больше.
# Отсекает "0.2.0" без v, "v0.2" без третьего числа, "v0.2.0-beta" с хвостом.
if ($Version -notmatch '^v\d+\.\d+\.\d+$') {
    throw "версия должна быть вида v1.2.3, а получено '$Version'"
}

# -----------------------------------------------------------------------------
# 3. Достаём текст версии из CHANGELOG.md
# -----------------------------------------------------------------------------

$changelogPath = Join-Path $repoRoot 'CHANGELOG.md'
if (-not (Test-Path $changelogPath)) {
    throw "не найден $changelogPath"
}

# -Encoding UTF8 обязателен: без него PowerShell 5.1 может прочитать файл
# как однобайтовую кодировку и превратить кириллицу в кракозябры.
$changelogLines = Get-Content -Path $changelogPath -Encoding UTF8

# Ищем строку вида "## v0.2.0 текст версии".
# [regex]::Escape нужен, потому что в номере версии есть точки,
# а точка в регулярном выражении означает "любой символ".
$pattern = '^##\s+' + [regex]::Escape($Version) + '(\s|$)'
$headingLine = $changelogLines | Where-Object { $_ -match $pattern } | Select-Object -First 1

if (-not $headingLine) {
    $hint = "в CHANGELOG.md нет записи для $Version.`n`n" +
            "Сначала опиши версию в CHANGELOG.md строкой вида:`n" +
            "    ## $Version краткое описание с маленькой буквы`n`n" +
            "Скрипт возьмёт этот текст и подставит его в коммит и в тег,`n" +
            "чтобы они гарантированно совпадали."
    throw $hint
}

# Убираем решётки и лишние пробелы — остаётся "v0.2.0 краткое описание".
$message = ($headingLine -replace '^##\s+', '').Trim()

# -----------------------------------------------------------------------------
# 4. Проверяем, что такого тега ещё нет
# -----------------------------------------------------------------------------

# 2>$null глушит сообщение об ошибке: отсутствие тега — это норма,
# ругаться тут не на что. Нас интересует только код возврата.
& git rev-parse -q --verify "refs/tags/$Version" 2>$null | Out-Null
if ($LASTEXITCODE -eq 0) {
    throw "тег $Version уже существует. Версии не переиспользуются: возьми следующий номер."
}

# -----------------------------------------------------------------------------
# 5. Показываем план
# -----------------------------------------------------------------------------

Write-Host ""
Write-Host "Версия: $Version" -ForegroundColor Cyan
Write-Host "Текст:  $message" -ForegroundColor Cyan
Write-Host ""
Write-Host "Что изменилось в рабочей папке:" -ForegroundColor Cyan

# --porcelain даёт короткий машинный вывод вместо развёрнутого человеческого.
$changes = & git status --porcelain
if ([string]::IsNullOrWhiteSpace($changes)) {
    Write-Host "  (ничего — тег будет поставлен на текущий коммит)" -ForegroundColor DarkGray
    $hasChanges = $false
} else {
    $changes | ForEach-Object { Write-Host "  $_" }
    $hasChanges = $true
}
Write-Host ""

if ($DryRun) {
    Write-Host "Это пробный прогон, ничего не сделано." -ForegroundColor Yellow
    Write-Host "Запусти без -DryRun, чтобы выпустить версию." -ForegroundColor Yellow
    return
}

# -----------------------------------------------------------------------------
# 6. Спрашиваем подтверждение
# -----------------------------------------------------------------------------

$answer = Read-Host "Выпускаем $Version? (y/n)"
if ($answer -ne 'y') {
    Write-Host "Отменено." -ForegroundColor Yellow
    return
}

# -----------------------------------------------------------------------------
# 7. Коммит, тег, отправка
# -----------------------------------------------------------------------------

# Сообщение передаём файлом через -F, а не аргументом через -m.
# Причина: аргументы командной строки проходят через кодировку консоли,
# и кириллица там иногда портится. Файл мы записали сами, в UTF-8,
# и git прочитает ровно те байты, которые мы положили.
$messageFile = Join-Path ([System.IO.Path]::GetTempPath()) "mgf-release-$Version.txt"
Write-Utf8NoBom -Path $messageFile -Text $message

try {
    if ($hasChanges) {
        Write-Host ""
        Write-Host "Коммит:" -ForegroundColor Cyan
        Invoke-Git add -A
        Invoke-Git commit -F $messageFile
    }

    Write-Host ""
    Write-Host "Тег:" -ForegroundColor Cyan
    # -a делает тег аннотированным: у него есть автор, дата и сообщение,
    # и в git он существует как отдельный объект. Лёгкий тег (просто
    # "git tag v0.4.0") — это только указатель на коммит, без всего
    # перечисленного. Для версий нужен именно аннотированный: по нему видно,
    # кто и когда выпустил релиз и что в нём.
    Invoke-Git tag -a $Version -F $messageFile

    Write-Host ""
    Write-Host "Отправка коммитов:" -ForegroundColor Cyan
    Invoke-Git push

    Write-Host ""
    Write-Host "Отправка тега:" -ForegroundColor Cyan
    # Тег отправляем ОТДЕЛЬНОЙ командой и ПО ИМЕНИ.
    #
    # Раньше здесь было "git push --follow-tags" — одна команда вместо двух.
    # Красиво, но на v0.3.0 коммит уехал, а тег остался дома, молча.
    # У --follow-tags есть условия (тег должен быть аннотированным, должен
    # указывать на отправляемый коммит, и флаг должен доехать до git через
    # PowerShell без потерь), и хотя бы одно из них не выполнилось.
    #
    # "git push origin v0.3.0" условий не имеет вообще: отправить вот этот
    # ref по имени. И заодно в команде нет ни одного аргумента с дефисами,
    # которые PowerShell норовит принять за свои параметры.
    #
    # Правило на будущее: когда выбираешь между умным и предсказуемым —
    # бери предсказуемое. Особенно там, где ошибка тихая.
    Invoke-Git push origin $Version

    # -------------------------------------------------------------------
    # 8. Проверяем, что тег действительно доехал
    # -------------------------------------------------------------------
    #
    # Отдельный шаг именно потому, что прошлый раз скрипт отрапортовал
    # "Готово", а тега на GitHub не было. Команда, которая говорит об успехе,
    # не проверив результат, — это команда, которой нельзя верить.
    #
    # ls-remote спрашивает у GitHub, какие ref'ы у него есть. Пусто в ответе
    # означает, что тега там нет, сколько бы мы его ни отправляли.
    Write-Host ""
    Write-Host "Проверяю, что тег дошёл до GitHub:" -ForegroundColor Cyan
    $remoteTag = & git ls-remote origin "refs/tags/$Version"
    if ($LASTEXITCODE -ne 0) {
        throw "не удалось опросить GitHub (git ls-remote вернул $LASTEXITCODE)"
    }
    if ([string]::IsNullOrWhiteSpace($remoteTag)) {
        throw "тег $Version на GitHub НЕ появился. Коммит, скорее всего, уехал. Отправь тег вручную: git push origin $Version"
    }
    Write-Host "  $remoteTag" -ForegroundColor DarkGray

    Write-Host ""
    Write-Host "Готово: $message" -ForegroundColor Green
}
finally {
    # finally выполняется всегда — и при успехе, и при ошибке.
    # Временный файл убираем в любом случае, чтобы не копить мусор.
    Remove-Item -Path $messageFile -ErrorAction SilentlyContinue
}
