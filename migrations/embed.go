// Пакет migrations существует ради одной строки — директивы //go:embed ниже.
//
// Что она делает. При компиляции Go возьмёт все файлы .sql из этой папки
// и зашьёт их прямо внутрь исполняемого файла. После сборки бинарник
// содержит миграции в себе и не зависит от того, лежит ли рядом папка
// migrations.
//
// Зачем так. В v1.0.0 приложение поедет в Docker-образ. Если бы миграции
// читались с диска, их пришлось бы отдельно копировать в образ и следить,
// чтобы версия файлов совпадала с версией кода. Со встроенными файлами
// такой проблемы нет по построению: они часть той же сборки.
//
// Пакет лежит в корне репозитория, а не в internal/, потому что //go:embed
// умеет брать файлы только из своей папки и вложенных — «наверх» ходить
// нельзя. А папку migrations/ хотелось оставить на виду, а не прятать.
package migrations

import "embed"

// FS — файловая система с миграциями, доступная только для чтения.
//
// Директива //go:embed должна стоять НЕПОСРЕДСТВЕННО перед переменной,
// без пустой строки между ними. Пустая строка — и Go молча посчитает её
// обычным комментарием, а переменная останется пустой.
//
//go:embed *.sql
var FS embed.FS
