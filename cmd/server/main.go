// Команда server — HTTP-сервис Music Genre Filter.
//
// Про структуру проекта. Папка cmd/ содержит точки входа: каждая её
// подпапка превращается в отдельную программу. Сейчас здесь только server,
// в v0.4.0 рядом появится cmd/music — утилита командной строки. Обе будут
// пользоваться одним и тем же кодом из internal/, просто запускать его
// по-разному.
//
// Папка internal/ — не наша выдумка, а правило самого Go: пакеты внутри
// internal/ невозможно импортировать из чужого проекта. Компилятор это
// запрещает. Удобно: видно, что является внутренней кухней, а что нет.
package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"github.com/joho/godotenv"

	"github.com/tulle-32/music-genre-filter/internal/config"
	"github.com/tulle-32/music-genre-filter/internal/storage"
	"github.com/tulle-32/music-genre-filter/internal/web"
)

// version — версия сборки. Значение можно подменить при компиляции
// (флаг -ldflags), что мы и сделаем в v1.0.0, чтобы собранный образ
// сам знал, из какого тега он собран.
var version = "0.2.0-dev"

// main — точка входа. Здесь она делает ровно одну вещь: вызывает run
// и решает, что делать с ошибкой.
//
// Почему не написать всё прямо в main. Потому что из main нельзя вернуть
// ошибку — можно только вызвать os.Exit, а os.Exit убивает программу
// мгновенно, не выполняя отложенные через defer вызовы. То есть все
// "закрыть соединение", "долить журнал на диск" просто не отработают.
// Поэтому вся работа живёт в run(), которая возвращает ошибку по-человечески,
// а main только печатает её и выходит.
func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "сервис остановлен с ошибкой: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	// -----------------------------------------------------------------------
	// 1. Настройки
	// -----------------------------------------------------------------------

	// Загружаем файл .env, если он есть. Это удобство для разработки:
	// в бою переменные окружения задаёт оркестратор, файла .env там нет.
	// Поэтому ошибку сознательно игнорируем — отсутствие файла это норма,
	// а не проблема.
	_ = godotenv.Load()

	cfg, err := config.Load()
	if err != nil {
		return err
	}

	// -----------------------------------------------------------------------
	// 2. Журнал
	// -----------------------------------------------------------------------

	// slog — структурированный журнал из стандартной библиотеки Go.
	// TextHandler пишет человекочитаемые строки, удобные в терминале.
	// В v1.2.0 переключим на JSONHandler: машине его разбирать проще,
	// а именно машина будет читать журналы в бою.
	log := slog.New(slog.NewTextHandler(os.Stdout, &slog.HandlerOptions{
		Level: cfg.LogLevel,
	}))

	log.Info("запускаемся",
		"версия", version,
		"адрес", cfg.HTTPAddr,
		"база", cfg.Database.SafeDSN(), // именно SafeDSN — без пароля
	)

	// -----------------------------------------------------------------------
	// 3. Контекст, который умирает по сигналу
	// -----------------------------------------------------------------------

	// Это самая важная часть файла, разберём подробно.
	//
	// Когда ты нажимаешь Ctrl+C или когда Docker останавливает контейнер,
	// операционная система посылает процессу сигнал: SIGINT в первом случае,
	// SIGTERM во втором. По умолчанию Go на такой сигнал просто убивает
	// программу на месте. Незавершённые запросы обрываются, соединения
	// с базой остаются висеть на стороне сервера.
	//
	// signal.NotifyContext перехватывает сигнал и вместо мгновенной смерти
	// отменяет контекст. Дальше мы сами решаем, что делать с оставшимся
	// временем: обычно "дообслужить текущие запросы и закрыться".
	//
	// Именно это называется graceful shutdown, и без него в Kubernetes
	// каждый перезапуск пода даёт горсть оборванных запросов у пользователей.
	ctx, stop := signal.NotifyContext(context.Background(),
		syscall.SIGINT,  // Ctrl+C в терминале
		syscall.SIGTERM, // docker stop, kubectl delete pod
	)
	defer stop() // вернуть обработку сигналов системе при выходе

	// -----------------------------------------------------------------------
	// 4. База данных
	// -----------------------------------------------------------------------

	db, err := storage.New(ctx, cfg.Database.DSN(), cfg.Database.MaxConns)
	if err != nil {
		return fmt.Errorf("подключение к базе: %w", err)
	}
	defer db.Close()

	// Пробуем достучаться до базы сразу, но НЕ падаем, если не вышло.
	// Причина та же, что и в комментарии к /health: база может стартовать
	// дольше приложения, это нормально. Мы просто честно пишем в журнал,
	// а /ready будет отдавать 503, пока база не поднимется.
	if err := db.Health(ctx); err != nil {
		log.Warn("база пока недоступна, продолжаем без неё", "ошибка", err)
	} else {
		log.Info("база отвечает")
	}

	// -----------------------------------------------------------------------
	// 5. HTTP-сервер
	// -----------------------------------------------------------------------

	server := &http.Server{
		Addr:    cfg.HTTPAddr,
		Handler: web.NewServer(log, db, version).Routes(),

		// Таймауты. Их отсутствие — самая распространённая ошибка в Go-сервисах,
		// и она тихая: всё работает, пока однажды медленный или зловредный
		// клиент не откроет тысячу соединений и не будет отправлять по байту
		// в минуту. Каждое такое соединение занимает горутину и память.
		// Без таймаутов сервис так и висит, пока не кончится память.
		ReadTimeout:  5 * time.Second,  // сколько ждём тело запроса целиком
		WriteTimeout: 10 * time.Second, // сколько даём себе на ответ
		IdleTimeout:  60 * time.Second, // сколько держим соединение без запросов
	}

	// Канал для ошибки сервера. Канал (chan) — способ передать значение
	// между горутинами. Горутина — очень лёгкий поток выполнения; их можно
	// запускать тысячами, в отличие от системных потоков.
	//
	// Размер буфера 1 здесь принципиален: запись в такой канал не блокирует
	// пишущего. Если бы канал был без буфера, а никто уже не читал, горутина
	// сервера навсегда зависла бы на записи — утечка.
	serverErrors := make(chan error, 1)

	// go перед вызовом функции запускает её в отдельной горутине.
	// Нам это нужно, потому что ListenAndServe блокирует до остановки сервера,
	// а нам параллельно надо ждать сигнал.
	go func() {
		log.Info("сервер слушает", "адрес", cfg.HTTPAddr)
		serverErrors <- server.ListenAndServe()
	}()

	// -----------------------------------------------------------------------
	// 6. Ждём: либо сервер упал, либо пришёл сигнал остановиться
	// -----------------------------------------------------------------------

	// select ждёт сразу на нескольких каналах и срабатывает на том,
	// который заговорит первым. Родной брат такого же select в сетевом
	// программировании на C, только для каналов.
	select {
	case err := <-serverErrors:
		// ListenAndServe при штатной остановке возвращает ErrServerClosed.
		// Это не ошибка, а способ сказать "меня попросили закрыться".
		// errors.Is умеет разворачивать цепочку обёрнутых через %w ошибок
		// и искать в ней нужную — сравнение через == так не умеет.
		if err != nil && !errors.Is(err, http.ErrServerClosed) {
			return fmt.Errorf("сервер не смог слушать: %w", err)
		}

	case <-ctx.Done():
		// Пришёл SIGINT или SIGTERM.
		log.Info("получен сигнал остановки, завершаем работу аккуратно",
			"даём_времени", cfg.ShutdownTimeout.String())

		// Новый контекст с ограничением по времени. Старый уже отменён
		// сигналом, а нам нужно ещё немного времени на аккуратное закрытие.
		shutdownCtx, cancel := context.WithTimeout(
			context.Background(), cfg.ShutdownTimeout)
		defer cancel()

		// Shutdown перестаёт принимать новые соединения и ждёт, пока
		// завершатся текущие запросы. Если за отведённое время не успели —
		// возвращает ошибку, и тогда рвём соединения принудительно.
		if err := server.Shutdown(shutdownCtx); err != nil {
			log.Error("аккуратно закрыться не успели, обрываем соединения",
				"ошибка", err)

			// Close, в отличие от Shutdown, рвёт всё немедленно.
			_ = server.Close()
			return fmt.Errorf("аварийная остановка сервера: %w", err)
		}
	}

	log.Info("остановлены штатно")
	return nil
}
