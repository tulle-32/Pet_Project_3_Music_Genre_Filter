// Пакет storage отвечает за всё, что связано с базой данных: подключение,
// пул соединений, а начиная с v0.3.0 — ещё и запросы.
//
// Сейчас здесь совсем немного: открыть пул и уметь ответить на вопрос
// "база вообще жива?". Этого хватает, чтобы проверить, что docker compose
// поднял PostgreSQL правильно и приложение до него достучалось.
package storage

import (
	"context"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

// DB — обёртка над пулом соединений к PostgreSQL.
//
// Почему обёртка, а не *pgxpool.Pool напрямую. Во-первых, чтобы остальной
// код зависел от НАШЕГО типа, а не от конкретной библиотеки: если однажды
// придётся сменить драйвер, менять придётся только этот пакет. Во-вторых,
// сюда удобно добавлять методы вроде Health() ниже.
type DB struct {
	// Pool со строчной буквы был бы приватным. Здесь заглавная, потому что
	// сгенерированный sqlc код (появится в v0.3.0) будет им пользоваться.
	Pool *pgxpool.Pool
}

// New открывает пул соединений к базе.
//
// Важная особенность pgxpool: он НЕ подключается к базе прямо здесь.
// Соединения открываются лениво, при первом реальном запросе. Это сделано
// специально, и нам это на руку: приложение стартует, даже если база ещё
// не поднялась. В контейнерах это обычное дело — сервис и база стартуют
// одновременно, и база почти всегда медленнее.
//
// Первый аргумент context.Context — это способ сказать долгой операции
// "хватит, отменяем". Контекст передаётся первым аргументом почти во все
// функции Go, которые делают что-то небыстрое: сеть, база, файлы.
func New(ctx context.Context, dsn string, maxConns int32) (*DB, error) {
	// ParseConfig разбирает строку подключения и проверяет её на осмысленность.
	// Если в DSN опечатка, мы узнаем об этом здесь, а не через полчаса работы.
	poolConfig, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		// %w — особый глагол форматирования: он "заворачивает" исходную ошибку
		// внутрь новой, сохраняя её для программной проверки выше по стеку.
		// Обычный %v просто превратил бы её в текст и потерял тип.
		return nil, fmt.Errorf("разбор строки подключения: %w", err)
	}

	poolConfig.MaxConns = maxConns

	// Сколько соединение может простаивать без дела, прежде чем его закроют.
	// Держать открытыми соединения, которыми никто не пользуется, — значит
	// занимать ресурсы на стороне сервера базы просто так.
	poolConfig.MaxConnIdleTime = 5 * time.Minute

	// Максимальный возраст соединения. Даже живое соединение полезно
	// периодически пересоздавать: это спасает от накопившихся проблем
	// на стороне сети и от ситуации, когда база уехала, а старые
	// соединения всё ещё указывают на старый адрес.
	poolConfig.MaxConnLifetime = time.Hour

	pool, err := pgxpool.NewWithConfig(ctx, poolConfig)
	if err != nil {
		return nil, fmt.Errorf("создание пула соединений: %w", err)
	}

	return &DB{Pool: pool}, nil
}

// Health проверяет, отвечает ли база прямо сейчас.
//
// Используется эндпоинтом /ready. Разница между /health и /ready именно
// в этом: health отвечает "процесс жив", ready — "процесс готов работать,
// все зависимости на месте". Ты это уже видел в первом проекте на
// liveness- и readiness-пробах Kubernetes, здесь ровно тот же смысл.
func (db *DB) Health(ctx context.Context) error {
	// Отдельный контекст с ограничением по времени. Если база подвисла,
	// проверка не должна висеть вместе с ней: она обязана быстро ответить
	// "не готов", чтобы оркестратор мог принять решение.
	ctx, cancel := context.WithTimeout(ctx, 2*time.Second)

	// defer откладывает вызов до выхода из функции — при любом выходе,
	// включая ранний return и панику. Идеально для освобождения ресурсов:
	// написал рядом с созданием и больше не боишься забыть.
	defer cancel()

	// Ping берёт соединение из пула и отправляет базе простейший запрос.
	if err := db.Pool.Ping(ctx); err != nil {
		return fmt.Errorf("база не отвечает: %w", err)
	}
	return nil
}

// Close закрывает все соединения пула. Вызывается при остановке приложения.
func (db *DB) Close() {
	db.Pool.Close()
}
