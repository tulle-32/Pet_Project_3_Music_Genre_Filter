// Пакет enrich описывает границу между "откуда берётся жанр исполнителя"
// и всем остальным приложением — по тому же принципу, что и пакет sources
// (см. internal/sources/source.go) для источников треков.
//
// Провайдеров жанров будет несколько (Last.fm сейчас, MusicBrainz в v0.8.0,
// Deezer позже — см. docs/ROADMAP.md и Р-004 в docs/DECISIONS.md), каждый —
// в своём подпакете (enrich/lastfm, дальше enrich/musicbrainz, enrich/deezer),
// согласно структуре в docs/ARCHITECTURE.md. У каждого свой формат ответа,
// свои лимиты, свой набор тегов. Код, который сводит эти теги к нашему
// справочнику жанров (internal/taxonomy, планируется) и считает уверенность
// (enrich/pipeline.go, туда же), не должен знать, откуда именно теги
// приехали — точно так же, как импорт треков не должен знать, приехал файл
// из ВК или с диска.
package enrich

import "context"

// Tag — один тег провайдера как есть, без перевода в наш справочник жанров.
//
// "Rock", "hard rock", "seen live" — все три в равной степени законные Tag.
// Разбираться, какие из них жанры, а какие нет (и переводить их в genre_id
// через таблицу genre_aliases) — задача другого, более высокого слоя, а не
// этого пакета. Здесь только "что сказал провайдер", без интерпретации.
type Tag struct {
	// Name — название тега как его вернул провайдер, в исходном регистре
	// и написании: "Alternative Rock", а не "alternative rock".
	Name string

	// Weight — насколько тег значим по мнению провайдера, обычно 0..100.
	// У Last.fm это "count" — что-то вроде популярности тега у слушателей
	// относительно самого популярного тега этого исполнителя. Не путать
	// с полем confidence в таблице artist_genres: то уже наша собственная
	// оценка, посчитанная из Weight и договорённостей между провайдерами.
	Weight int
}

// GenreProvider — договорённость, которой обязан соответствовать любой
// источник тегов для обогащения жанрами.
//
// Интерфейс крошечный по той же причине, что и TrackSource: чем меньше
// методов обязана реализовать новая интеграция, тем дешевле её добавить.
type GenreProvider interface {
	// Name — короткое машинное имя провайдера для журналов и базы:
	// "lastfm", "musicbrainz", "deezer". Попадает в колонку provider
	// таблиц artist_genres, track_genres и provider_cache.
	Name() string

	// TopTags возвращает теги исполнителя, как их видит провайдер, ВМЕСТЕ
	// с сырыми байтами ответа, из которых они разобраны.
	//
	// Зачем нужны именно сырые байты, а не только уже готовые Tag: ради
	// кэша (provider_cache, Р-005 в docs/DECISIONS.md и комментарий к
	// таблице в 00001_initial_schema.sql — "чтобы пересчитать жанры из
	// кэша, вообще не обращаясь в сеть, когда поменяем логику разбора
	// тегов"). Если бы кэшировались только уже посчитанные Tag, эта цель
	// была бы недостижима: баг или улучшение в разборе конкретного
	// провайдера (например, в lastfm.unmarshalTags) не отразился бы на
	// уже закэшированных исполнителях, пока не истечёт 30-дневный срок
	// и программа не сходит в сеть заново.
	//
	// Принимает НОРМАЛИЗОВАННОЕ имя исполнителя — конкретно то, что
	// возвращает normalize.PrimaryArtist (Р-011 в docs/DECISIONS.md):
	// "Miyagi", а не "Miyagi feat. Andy Panda" и не ключ сравнения
	// "miyagi". Сам провайдер не занимается очисткой строк, это не его
	// забота. Пустой срез без ошибки — законный ответ: значит провайдер
	// исполнителя не знает, это не сбой.
	TopTags(ctx context.Context, artistName string) (tags []Tag, raw []byte, err error)

	// ParseTopTags разбирает сырые байты — те же самые, что вернул TopTags,
	// — в []Tag. Пайплайн (pipeline.go, этот же пакет) вызывает её на
	// байтах, поднятых из кэша, вместо того чтобы снова стучаться в сеть.
	// Раз кэш работает через GenreProvider вообще, а не через конкретный
	// internal/enrich/lastfm, разбор тоже обязан быть частью интерфейса —
	// иначе pipeline.go пришлось бы знать имя пакета конкретного
	// провайдера, а именно от этого знания интерфейс и должен избавлять.
	ParseTopTags(raw []byte) ([]Tag, error)
}
