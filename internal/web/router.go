// Пакет web содержит всё, что относится к HTTP: маршруты, обработчики
// запросов, а позже — шаблоны страниц.
//
// Здесь нет ни одной сторонней библиотеки. Начиная с Go 1.22 встроенный
// маршрутизатор net/http умеет то, ради чего раньше тащили chi или gorilla:
// разбирать метод запроса и параметры пути. Для нашей задачи этого хватает
// с запасом, а каждая невзятая зависимость — это то, что не сломается
// при обновлении и не придётся объяснять на собеседовании.
package web

import (
	"context"
	"log/slog"
	"net/http"
	"time"
)

// healthChecker описывает то единственное, что обработчикам нужно знать
// о базе данных: умеет ли она отвечать.
//
// Это интерфейс — самая важная конструкция в Go. Интерфейс перечисляет
// методы, ничего не говоря о том, кто их реализует. Тип storage.DB подходит
// под этот интерфейс просто потому, что у него есть метод Health с такой
// сигнатурой. Ему не нужно ничего объявлять или наследовать: в Go
// соответствие интерфейсу проверяется автоматически, по факту наличия методов.
//
// Практическая польза именно здесь: пакет web не импортирует пакет storage.
// Он не знает про PostgreSQL, pgx и строки подключения вообще ничего.
// А в тестах вместо настоящей базы можно подсунуть заглушку из десяти строк,
// у которой есть метод Health — и обработчик этого не заметит.
//
// Тот же приём мы применим к источникам треков (TrackSource) и к провайдерам
// жанров (GenreProvider). Это несущая идея всей архитектуры проекта.
type healthChecker interface {
	Health(ctx context.Context) error
}

// Server держит всё, что нужно обработчикам для работы.
//
// Такую структуру обычно называют "зависимости" или "контекст приложения".
// Альтернатива — глобальные переменные — работает ровно до того момента,
// когда понадобится написать тест или запустить два экземпляра рядом.
type Server struct {
	log     *slog.Logger
	db      healthChecker
	version string
	started time.Time
}

// NewServer собирает Server. Обычная функция-конструктор: в Go нет
// специального синтаксиса для конструкторов, есть договорённость называть
// такие функции New или NewЧтоТо.
func NewServer(log *slog.Logger, db healthChecker, version string) *Server {
	return &Server{
		log:     log,
		db:      db,
		version: version,
		started: time.Now(),
	}
}

// Routes описывает, какой адрес какому обработчику достаётся.
//
// Возвращает http.Handler — это тоже интерфейс, с единственным методом
// ServeHTTP. Всё, что умеет обрабатывать HTTP-запросы в Go, реализует его.
func (s *Server) Routes() http.Handler {
	mux := http.NewServeMux()

	// Строка "GET /health" — это шаблон маршрута. До Go 1.22 метод запроса
	// приходилось проверять внутри обработчика руками; теперь он часть
	// шаблона, и на POST /health маршрутизатор сам ответит 405.
	mux.HandleFunc("GET /health", s.handleHealth)
	mux.HandleFunc("GET /ready", s.handleReady)

	// Оборачиваем весь набор маршрутов в middleware — промежуточный слой,
	// который выполняется до и после обработчика. Здесь он пишет в журнал
	// каждый запрос. Порядок обёрток важен: тот, кто снаружи, отработает первым.
	return s.withLogging(mux)
}

// withLogging — middleware, записывающий каждый запрос в журнал.
//
// Устроен так: принимает обработчик и возвращает ДРУГОЙ обработчик, который
// делает свои дела и вызывает исходный. Матрёшка. Именно так в Go делается
// всё сквозное: журналирование, аутентификация, ограничение частоты запросов,
// сбор метрик — всё это слои вокруг основного обработчика.
func (s *Server) withLogging(next http.Handler) http.Handler {
	// http.HandlerFunc — приведение обычной функции к типу, реализующему
	// интерфейс http.Handler. Приём, экономящий объявление отдельного типа.
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		start := time.Now()

		// Настоящий http.ResponseWriter не помнит, какой код ответа в него
		// записали. Поэтому подменяем его своей обёрткой, которая запоминает.
		rec := &statusRecorder{ResponseWriter: w, status: http.StatusOK}

		// Вот здесь вызывается собственно обработчик.
		next.ServeHTTP(rec, r)

		// Журнал пишем структурированно: не склеенной строкой, а парами
		// "ключ — значение". Такую запись можно потом фильтровать и считать
		// машиной. Строку "GET /health 200 за 1.2ms" машиной разбирать больно.
		s.log.Info("http-запрос",
			"метод", r.Method,
			"путь", r.URL.Path,
			"статус", rec.status,
			"длительность", time.Since(start).String(),
		)
	})
}

// statusRecorder запоминает код ответа, проходящий сквозь него.
//
// Строка "http.ResponseWriter" внутри структуры без имени поля — это
// встраивание (embedding). Оно означает: у statusRecorder автоматически
// появляются все методы http.ResponseWriter. Мы переопределяем только один,
// WriteHeader, а остальные достаются даром. Это ближайшее, что есть в Go
// к наследованию, но работает оно через композицию.
type statusRecorder struct {
	http.ResponseWriter
	status int
}

// WriteHeader перехватывает установку кода ответа, запоминает его
// и передаёт дальше настоящему ResponseWriter.
func (r *statusRecorder) WriteHeader(code int) {
	r.status = code
	r.ResponseWriter.WriteHeader(code)
}
