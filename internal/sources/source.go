// Пакет sources описывает границу между "откуда приехали треки" и всем
// остальным приложением.
//
// Это самое важное место в архитектуре проекта, и вот почему.
//
// Официальный API ВКонтакте музыку не отдаёт. Все обходные пути хрупкие:
// они опираются на внутренние адреса, у которых нет обещаний совместимости.
// Любой из них может перестать работать в любой вторник.
//
// Если бы код импорта был написан "внутрь ВК" напрямую, то в день поломки
// умер бы весь проект. Поэтому здесь объявлен интерфейс: договорённость
// о том, ЧТО источник обязан уметь, без единого слова о том, КАК он это
// делает. Файл, страница ВК, официальный архив выгрузки — три разные
// реализации одной договорённости.
//
// Всё, что правее этой границы — нормализация, база, обогащение жанрами,
// фильтр, веб-интерфейс — про ВКонтакте не знает ничего.
package sources

import "context"

// RawTrack — трек в том виде, в каком его отдал источник.
//
// Слово Raw в названии не случайно: здесь всё сырое, как пришло, со всеми
// лишними пробелами, скобками и разнобоем в регистре. Никакой обработки
// на этом уровне не происходит — за неё отвечает пакет normalize,
// и произойдёт она уже после того, как источник отработал.
//
// Разделение специально жёсткое. Источник знает, как достать данные,
// и не знает, что с ними делать дальше. Нормализация знает, как чистить
// строки, и не знает, откуда они взялись. Каждый занят своим делом.
type RawTrack struct {
	// Artist — исполнитель как есть: "  NIRVANA ", "Miyagi feat. Andy Panda".
	Artist string

	// Title — название как есть: "Smells Like Teen Spirit (Official Video)".
	Title string

	// DurationSec — длительность в секундах. Ноль означает "источник
	// не сообщил", а не "трек длиной ноль секунд".
	DurationSec int

	// SourceID — идентификатор трека внутри источника, если он есть.
	// У ВК это что-то вроде "148598066_456239017", у файла может
	// не быть вовсе. Нужен, чтобы при повторной выгрузке понимать,
	// что это тот же самый трек, даже если название слегка изменилось.
	SourceID string
}

// TrackSource — договорённость, которой обязан соответствовать любой
// источник треков.
//
// В Go интерфейс — это просто список методов. Ничего наследовать и нигде
// регистрироваться не нужно: тип подходит под интерфейс автоматически,
// если у него есть все перечисленные методы с такими же сигнатурами.
// Проверяет это компилятор, на этапе сборки.
//
// Интерфейс намеренно крошечный. Чем меньше методов, тем проще написать
// новую реализацию и тем меньше поводов её менять. Разрастись он может
// только под давлением реальной необходимости, а не "на будущее".
type TrackSource interface {
	// Name возвращает короткое имя источника для журналов и базы:
	// "file", "vk", "archive". Попадает в колонку source_name.
	Name() string

	// Ref возвращает то, откуда именно брались треки: путь к файлу
	// или ссылку на страницу. Попадает в колонку source_ref и в журнал
	// импортов — чтобы через месяц было понятно, откуда взялась библиотека.
	Ref() string

	// Fetch отдаёт все треки источника.
	//
	// Контекст первым аргументом — стандарт Go для всего, что может
	// выполняться долго. Выкачивание двух тысяч треков из ВК занимает
	// минуты, и её надо уметь прервать по Ctrl+C, не дожидаясь конца.
	// Файловый источник отрабатывает мгновенно, но сигнатура одна на всех:
	// в этом и смысл интерфейса.
	Fetch(ctx context.Context) ([]RawTrack, error)
}
